// Disposable browser profile and demo document; never writes the user's inventory.
const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const path=require('node:path');

(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.CHROME_BIN?{executablePath:process.env.CHROME_BIN}:{channel:'chrome'})});
  try{
    const context=await browser.newContext({viewport:{width:1360,height:900}}),page=await context.newPage(),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto((process.env.METRICS_URL||'http://127.0.0.1:5215')+'/?section=personal-metrics');
    await page.waitForFunction(()=>window.__inventory);
    if(await page.locator('.dt-dialog[open]').count())await page.locator('.dt-dialog').getByRole('button',{name:'Пропустить обзор'}).click();
    if(!await page.locator('.pm-survey-inline').count())await page.getByRole('button',{name:'Заполнить за сегодня'}).click();
    const survey=()=>page.locator('.pm-survey-inline');
    for(const answer of ['Хорошо','Средне','Немного','Хорошо'])await survey().getByRole('button',{name:answer,exact:true}).click();
    assert.match(await survey().innerText(),/На что ушло занятое время/);
    await survey().locator('.pm-time-choice').nth(0).getByRole('button',{name:'4–6 ч'}).click();
    await survey().locator('.pm-time-choice').nth(1).getByRole('button',{name:'до 1 ч'}).click();
    await survey().locator('.pm-time-choice').nth(2).getByRole('button',{name:'1–2 ч'}).click();
    await survey().getByRole('button',{name:'Далее'}).click();
    await survey().getByRole('button',{name:'Умеренно'}).click();
    await survey().getByRole('button',{name:'Хорошо'}).click();
    assert.match(await survey().innerText(),/Контекст дня/);
    await survey().locator('.pm-tag-group').nth(0).getByRole('button',{name:'Работа'}).click();
    await survey().locator('.pm-tag-group').nth(1).getByRole('button',{name:'Прогулка'}).click();
    await survey().getByRole('button',{name:'Сохранить отметку'}).click();
    await page.waitForFunction(()=>!document.querySelector('.pm-survey-inline'));
    const entry=await page.evaluate(()=>window.__inventory.document.personalMetrics.entries[0]);
    assert.deepEqual([entry.mood,entry.energy,entry.tension,entry.productivity,entry.busyMinutes,entry.loadScore,entry.rest],[4,3,2,4,420,3,4]);
    assert.deepEqual(entry.causes,['work']);assert.deepEqual(entry.recovery,['walk']);
    assert.equal(await page.locator('.pm-card').count(),9);
    await page.getByRole('button',{name:'30 дней'}).click();
    assert.equal(await page.locator('.pm-card').first().locator('.pm-trend i').count(),30);
    await page.getByRole('button',{name:'Записать массу'}).click();
    await page.getByLabel('Масса тела в килограммах').fill('72.5');
    await page.locator('.pm-weight-panel').getByRole('button',{name:'Сохранить'}).click();
    await page.waitForFunction(()=>window.__inventory.document.personalMetrics.weight?.length===1);
    await page.locator('.pm-tabs').getByRole('button',{name:'История'}).click();
    assert.equal(await page.locator('.pm-history-row').count(),1);
    await page.locator('.pm-tabs').getByRole('button',{name:'Источники'}).click();
    const day=entry.date,xml=`<HealthData><Record type="HKQuantityTypeIdentifierStepCount" sourceName="iPhone" unit="count" startDate="${day} 10:00:00 +0300" endDate="${day} 10:05:00 +0300" value="8123"/></HealthData>`;
    await page.locator('.pm-file').setInputFiles({name:'export.xml',mimeType:'text/xml',buffer:Buffer.from(xml)});
    await page.waitForFunction(()=>window.__inventory.document.personalMetrics.health.length===1);
    await page.reload();await page.waitForFunction(()=>window.__inventory);
    assert.equal(await page.locator('.pm-survey-inline').count(),0);
    assert.match(await page.locator('.pm-week').innerText(),/Масса тела/);
    await page.screenshot({path:path.resolve('docs/images/personal-metrics-overview.png')});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.resolve('docs/images/personal-metrics-mobile.png')});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.locator('.pm-tabs').getByRole('button',{name:'Источники'}).click();
    await page.getByRole('button',{name:'Внести вручную'}).click();
    await page.locator('.pm-health-panel').getByRole('button',{name:'Нет данных'}).click();
    await page.getByLabel('Точное значение: Шаги').fill('9000');
    await page.locator('.pm-health-panel').getByRole('button',{name:'Применить точное значение'}).click();
    await page.locator('.pm-health-panel').getByRole('button',{name:'Нет данных'}).click();
    await page.waitForFunction(()=>window.__inventory.document.personalMetrics.health[0].steps===9000);
    await page.locator('.pm-file').setInputFiles({name:'export.xml',mimeType:'text/xml',buffer:Buffer.from(xml)});
    await page.locator('.iv-toast').getByText('Из Apple Health загружено дней: 1').waitFor();
    assert.equal(await page.evaluate(()=>window.__inventory.document.personalMetrics.health[0].steps),9000);
    await page.getByRole('button',{name:'Выбрать календари'}).click();
    await page.getByRole('alert').getByText(/Календари доступны в приложении/).waitFor();
    assert.deepEqual(errors,[]);
    console.log('Personal metrics UI: seven-card survey, context, time split, trends, weight, history, Apple Health and mobile passed.');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
